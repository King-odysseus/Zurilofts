/**
 * Writes public/third-party-notices.txt: every package the site depends on
 * (walked from package.json "dependencies"), with its licence and copyright
 * line, followed by each distinct licence text once.
 *
 * MIT, BSD and Apache licences require their notice to travel with copies of
 * the code; the bundled site is such a copy, so the file is served from the
 * site root and linked from the Photo credits page.
 *
 * Run: npm run notices   (re-run after changing dependencies)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nodeModules = path.join(root, 'node_modules');
const rootPkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

const LICENCE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md', 'license', 'license.md', 'License.md'];

function readPackage(name, fromDir) {
  // Node resolution: nearest node_modules walking upward from the requirer.
  for (let dir = fromDir; dir.startsWith(root); dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
  }
  return null;
}

function licenceName(pkg) {
  const raw = pkg.license ?? pkg.licenses;
  if (!raw) return 'UNKNOWN';
  if (typeof raw === 'string') return raw;
  if (Array.isArray(raw)) return raw.map((entry) => entry.type ?? String(entry)).join(' OR ');
  return raw.type ?? 'UNKNOWN';
}

function findLicenceText(dir) {
  const hit = LICENCE_FILES.find((file) => fs.existsSync(path.join(dir, file)));
  return hit ? fs.readFileSync(path.join(dir, hit), 'utf8').trim() : '';
}

const seen = new Map();
function walk(name, fromDir) {
  const dir = readPackage(name, fromDir);
  if (!dir || seen.has(dir)) return;
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const text = findLicenceText(dir);
  const copyright = text.split(/\r?\n/).find((line) => /copyright/i.test(line))?.trim() ?? '';
  seen.set(dir, { name: pkg.name, version: pkg.version, licence: licenceName(pkg), copyright, text });
  const deps = { ...pkg.dependencies, ...pkg.optionalDependencies };
  for (const dep of Object.keys(deps)) walk(dep, dir);
}

for (const dep of Object.keys(rootPkg.dependencies ?? {})) walk(dep, root);

const entries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const out = [
  'ZuriLofts third-party notices',
  'Generated by scripts/generate-notices.mjs. The packages below are used under their own licences.',
  '',
];

for (const entry of entries) {
  out.push(`${entry.name}@${entry.version} - ${entry.licence}${entry.copyright ? ` - ${entry.copyright}` : ''}`);
}

// Each distinct text once; ten thousand lines of the same MIT paragraph help nobody.
const texts = new Map();
for (const entry of entries) {
  if (!entry.text) continue;
  const key = entry.text.replace(/Copyright[^\n]*/gi, '').replace(/\s+/g, ' ').trim();
  if (!texts.has(key)) texts.set(key, { licence: entry.licence, text: entry.text, users: [] });
  texts.get(key).users.push(entry.name);
}
out.push('', '='.repeat(72), 'Licence texts', '='.repeat(72));
for (const { licence, text, users } of texts.values()) {
  out.push('', `${licence}, used by: ${users.slice(0, 8).join(', ')}${users.length > 8 ? `, and ${users.length - 8} more` : ''}`, '-'.repeat(72), text);
}

const missing = entries.filter((entry) => !entry.text).map((entry) => `${entry.name}@${entry.version} (${entry.licence})`);
if (missing.length) {
  out.push('', '='.repeat(72), 'Packages that ship no licence file; licence taken from package.json', '='.repeat(72), ...missing);
}

fs.writeFileSync(path.join(root, 'public', 'third-party-notices.txt'), `${out.join('\n')}\n`);
console.log(`Wrote ${entries.length} packages, ${texts.size} distinct licence texts, ${missing.length} without a licence file.`);
